import * as THREE from 'three';
import { createStandardPalette } from './craftForms';
import { resolveObjectArchetype } from './archetypeResolver';
import { buildSculpt, lookupPrioritySculptSpec, SculptSpec } from './sculptSpec';

export interface ProceduralMeshOptions {
  category?: string;
  name?: string;
  tokenPrompt?: string;
  colorHex?: number;
  isSelected?: boolean;
  isGhostWireframe?: boolean;
  sculpt?: SculptSpec;
  /** Legacy alias for sculpt */
  partGraph?: any;
}

/**
 * Universal Procedural Actor Factory.
 * Grounded in the declarative SculptSpec object-reasoning specification and 207+ parametric 3D blueprints.
 * Synthesizes and builds authentic, parametric geometric parts (blob, box, cylinder, lathe, extrude, tube)
 * with tactile PBR materials.
 */
export function createProceduralActorMesh(options: ProceduralMeshOptions): THREE.Group {
  const {
    category = 'custom',
    name = '',
    tokenPrompt = '',
    isGhostWireframe = false,
    sculpt,
    partGraph,
  } = options;

  // 1. Establish authentic multi-material PBR Palette (selection highlight is handled by the base ring & gizmo, never by painting the model amber)
  const palette = createStandardPalette();

  // 2. Objects generated by the LLM object reasoner or priority bespoke sculpts build from their SculptSpec.
  const activeSculpt = sculpt || (partGraph ? partGraph : null);
  const reasoned = activeSculpt || lookupPrioritySculptSpec(tokenPrompt) || lookupPrioritySculptSpec(name);

  // 3. Resolve curated / quick-add items through the 207+ parametric 3D blueprint catalog.
  const resolution = resolveObjectArchetype(`${name} ${tokenPrompt}`, category);

  // 4. Build the physical assembly
  const kit = reasoned ? buildSculpt(reasoned) : resolution.build(palette);
  const root = kit.group;

  // 5. Ghost Wireframe Mode for viewpoint cameras and stage alignment
  if (isGhostWireframe) {
    const ghostMat = new THREE.MeshBasicMaterial({
      color: 0x06b6d4,
      wireframe: true,
      transparent: true,
      opacity: 0.45,
    });
    root.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        (child as THREE.Mesh).material = ghostMat;
        child.castShadow = false;
        child.receiveShadow = false;
      }
    });
  }

  // 6. Attach Authoritative Physical Kinematics Hook & 3Dviz Reasoning Trace
  root.userData.update = kit.update || ((_dt: number) => {});
  root.userData.reasoningTrace = resolution.reasoningTrace;
  root.userData.archetypeId =
    resolution.matchedArchetype?.id || resolution.reasoningTrace.step05Routing.source;
  root.userData.reasonedGraph = !!reasoned;
  root.userData.sculptSpec = reasoned || null;

  return root;
}

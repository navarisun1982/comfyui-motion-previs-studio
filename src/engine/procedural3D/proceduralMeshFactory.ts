import * as THREE from 'three';
import { createStandardPalette } from './craftForms';
import { resolveObjectArchetype } from './archetypeResolver';
import { buildPartGraph, lookupPartGraph, PartGraph } from './partGraph';

export interface ProceduralMeshOptions {
  category?: string;
  name?: string;
  tokenPrompt?: string;
  colorHex?: number;
  isSelected?: boolean;
  isGhostWireframe?: boolean;
  partGraph?: PartGraph;
}

/**
 * 3Dviz Pro Max Universal Procedural Actor Factory.
 * Grounded in the 3Dviz Pro Max object-reasoning specification (scripts/search.py and references/object-craft.md).
 * Replaces ad-hoc string regex cascades with probabilistic BM25 token matching,
 * sub-word root stemming, query expansion, and first-principles morphometric synthesis.
 */
export function createProceduralActorMesh(options: ProceduralMeshOptions): THREE.Group {
  const {
    category = 'custom',
    name = '',
    tokenPrompt = '',
    colorHex = 0x38bdf8,
    isSelected = false,
    isGhostWireframe = false,
    partGraph,
  } = options;

  // 1. Establish PBR Palette matching the actor's visual tone & selection state
  const palette = createStandardPalette(isSelected ? 0xf59e0b : colorHex);

  // 2. Objects generated by the object reasoner carry their own part graph: build exactly that.
  const reasoned = partGraph || lookupPartGraph(tokenPrompt) || lookupPartGraph(name);

  // 3. Otherwise resolve curated / quick-add items through the kit catalog.
  const resolution = reasoned
    ? null
    : resolveObjectArchetype(`${name} ${tokenPrompt}`, category);

  // 4. Build the physical assembly
  const kit = reasoned ? buildPartGraph(reasoned) : resolution!.build(palette);
  const root = kit.group;

  // 4. Ghost Wireframe Mode for viewpoint cameras and stage alignment
  if (isGhostWireframe) {
    const ghostMat = new THREE.MeshBasicMaterial({
      color: 0x06b6d4,
      wireframe: true,
      transparent: true,
      opacity: 0.45,
    });
    root.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        (child as THREE.Mesh).material = ghostMat;
        child.castShadow = false;
        child.receiveShadow = false;
      }
    });
  }

  // 5. Attach Authoritative Physical Kinematics Hook & 3Dviz Reasoning Trace
  if (kit.update) {
    root.userData.update = kit.update;
  }
  root.userData.reasoningTrace = resolution?.reasoningTrace;
  root.userData.reasonedGraph = !!reasoned;

  return root;
}
